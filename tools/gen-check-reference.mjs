// Generates the per-check reference pages under docs/checks/reference/ from the check catalog, so a
// published page never becomes a third copy of the truth: each fact keeps one home — severity, needs,
// and standards live in the check's `meta(...)` block, the explanation lives in its prose page under
// docs/checks/, and a reference page only composes the two.
//
//   npm run build && npm run reference:build          # rewrite docs/checks/reference/
//   npm run build && npm run reference:build --check  # fail when a page drifts, is missing, or is stale
//
// Discovery reads the built catalog (the same modules tools/gen-registries.mjs collects, plus the
// suppression checks the engine always runs). Output is deterministic across platforms: pages are
// sorted by check ID, prose is embedded with LF endings and one trailing newline, nothing is dated.

import { existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseArgs } from "node:util";

import { discoverChecks } from "./gen-registries.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const VERIFY_DIST = join(root, "packages", "verify", "dist");
const REFERENCE_DIR = join(root, "docs", "checks", "reference");
const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** Which CLI flag turns a gated need on. `html` and `files` are read offline by default. */
const GATES = { browser: "--rendered", network: "--network" };

const needsText = (needs) =>
  needs.map((need) => (GATES[need] ? `\`${need}\` (only with \`${GATES[need]}\`)` : `\`${need}\``)).join(", ");

/** The prose of docs/checks/<id>.md without its leading `# <id>` line, LF-normalized, one trailing newline. */
export function proseBody(id, prose) {
  const text = prose.replace(/\r\n/g, "\n");
  const h1 = `# ${id}\n`;
  if (!text.startsWith(h1)) throw new Error(`docs/checks/${id}.md must start with "# ${id}"`);
  return text.slice(h1.length).trim() + "\n";
}

/** One reference page: a catalog-derived header over the prose embedded verbatim. */
export function renderReference(meta, sourceRel, prose) {
  const { id, title, severity, needs, standards } = meta;
  const header = [
    "<!-- GENERATED by tools/gen-check-reference.mjs — do not edit by hand. -->",
    `<!-- Composed from the check catalog (\`${sourceRel}\`) and the prose in \`docs/checks/${id}.md\`. -->`,
    "<!-- Edit one of those, then run `npm run build && npm run reference:build`. -->",
    "",
    `# ${id} — ${title}`,
    "",
    `- **Check ID:** \`${id}\``,
    `- **Default severity:** \`${severity}\`; users can override it in \`seaworthy.config.json\`.`,
    `- **Needs:** ${needsText(needs)}`,
    `- **Standards:** ${standards.length > 0 ? standards.join(", ") : "none"}`,
    `- **Source module:** \`${sourceRel}\``,
    `- **Prose page:** [\`docs/checks/${id}.md\`](../${id}.md) — embedded below verbatim; write it there, never here.`,
    "",
  ].join("\n");
  return header + "\n" + proseBody(id, prose);
}

/** The catalog as [{ meta, sourceRel }], sorted by check ID. Needs `npm run build` first. */
export async function loadCatalog() {
  if (!existsSync(join(VERIFY_DIST, "src", "checks", "registry.js"))) {
    throw new Error(`the build is missing: ${relative(root, VERIFY_DIST)}. Run \`npm run build\` first.`);
  }
  const filesById = new Map((await discoverChecks()).map((c) => [c.id, `packages/verify/src/checks/${c.file.replace(/\.js$/, ".ts")}`]));
  const { builtInChecks } = await import(pathToFileURL(join(VERIFY_DIST, "src", "checks", "registry.js")).href);
  const { SUPPRESSION_CHECKS } = await import(pathToFileURL(join(VERIFY_DIST, "src", "suppress.js")).href);
  return [...builtInChecks, ...SUPPRESSION_CHECKS]
    .map((check) => ({ meta: check.meta, sourceRel: filesById.get(check.meta.id) ?? "packages/verify/src/suppress.ts" }))
    .sort((a, b) => byCodeUnit(a.meta.id, b.meta.id));
}

/** Every page to generate, as { "docs/checks/reference/<id>.md" -> text }. A missing prose page fails the run. */
export function generatedFiles(rootDir, catalog) {
  const files = new Map();
  for (const { meta, sourceRel } of catalog) {
    const prosePath = join(rootDir, "docs", "checks", `${meta.id}.md`);
    if (!existsSync(prosePath)) throw new Error(`reference: docs/checks/${meta.id}.md is missing; every catalog check needs a prose page`);
    files.set(join("docs", "checks", "reference", `${meta.id}.md`), renderReference(meta, sourceRel, readFileSync(prosePath, "utf8")));
  }
  return files;
}

async function main() {
  const { values } = parseArgs({ options: { check: { type: "boolean" } } });
  const catalog = await loadCatalog();
  const files = generatedFiles(root, catalog);
  const existing = existsSync(REFERENCE_DIR)
    ? readdirSync(REFERENCE_DIR).filter((f) => f.endsWith(".md") && f !== "README.md").map((f) => join("docs", "checks", "reference", f))
    : [];
  const stale = existing.filter((rel) => !files.has(rel));
  const problems = [];
  for (const [rel, content] of files) {
    const path = join(root, rel);
    if (!existsSync(path)) problems.push(`missing ${rel}`);
    else if (readFileSync(path, "utf8") !== content) problems.push(`${rel} is out of date`);
  }
  for (const rel of stale) problems.push(`stale ${rel}: no catalog check generates it any more`);
  if (values.check) {
    if (problems.length > 0) {
      console.error(problems.map((p) => `reference: ${p}`).join("\n"));
      console.error("reference: regenerate with `npm run build && npm run reference:build` and commit the result.");
      process.exit(1);
    }
    console.log(`OK: reference (${files.size} generated pages in sync with the catalog)`);
    return;
  }
  mkdirSync(REFERENCE_DIR, { recursive: true });
  for (const [rel, content] of files) writeFileSync(join(root, rel), content);
  for (const rel of stale) rmSync(join(root, rel));
  console.log(`reference: wrote ${files.size} pages from ${catalog.length} checks under docs/checks/reference/`);
}

// Run only when executed directly, not when imported by tests.
function invokedDirectly() {
  const entry = process.argv[1];
  if (!entry) return false;
  try {
    return realpathSync(entry) === fileURLToPath(import.meta.url);
  } catch {
    return false;
  }
}

if (invokedDirectly()) await main();
