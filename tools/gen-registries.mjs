// Regenerates the two generated registries from the built modules they collect, so adding a
// check or a format means adding a module and running this — never editing a shared index.
//
//   npm run build && node tools/gen-registries.mjs           # rewrite both registries
//   npm run build && node tools/gen-registries.mjs --check   # fail when one is stale
//
// Discovery is value-based: every built module under packages/verify/dist/src/checks and
// dist/src/formats is imported and inspected, so factory-built checks (links.external) and
// data-only modules (aria-data.ts, base.ts) need no exceptions. Registry order is explicit —
// checks by check ID, formats by format ID — never the filesystem's.

import { existsSync, readdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseArgs } from "node:util";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const VERIFY = join(root, "packages", "verify");
const CHECKS_DIST = join(VERIFY, "dist", "src", "checks");
const FORMATS_DIST = join(VERIFY, "dist", "src", "formats");
const CHECKS_REGISTRY = join(VERIFY, "src", "checks", "registry.ts");
const FORMATS_REGISTRY = join(VERIFY, "src", "formats", "registry.ts");

/** .js files to import, sorted, skipping the generated registries and the type-only base module.
 * A dist module whose source is gone is skipped (not imported), so removing a check stays workable:
 * the generator rewrites the registry without it, and the next `npm run build` succeeds and prunes. */
function listModules(dir, skip) {
  if (!existsSync(dir)) throw new Error(`the build is missing: ${dir}. Run \`npm run build\` first.`);
  const srcDir = join(VERIFY, "src", relative(join(VERIFY, "dist", "src"), dir));
  return readdirSync(dir)
    .filter((f) => f.endsWith(".js") && !skip.includes(f))
    .filter((f) => {
      if (existsSync(join(srcDir, f.replace(/\.js$/, ".ts")))) return true;
      console.error(`gen-registries: skipping ${join(dir, f)} — no source for it; run \`npm run build\` to prune the build output.`);
      return false;
    })
    .sort();
}

const isCheck = (value) => typeof value === "object" && value !== null && typeof value.meta?.id === "string" && typeof value.run === "function";

/** Every Check exported by any checks module, sorted by check ID. */
export async function discoverChecks(dir = CHECKS_DIST) {
  const byId = new Map();
  for (const file of listModules(dir, ["index.js", "registry.js"])) {
    const module = await import(pathToFileURL(join(dir, file)).href);
    for (const [name, value] of Object.entries(module)) {
      if (!isCheck(value)) continue;
      const known = byId.get(value.meta.id);
      if (known) throw new Error(`duplicate check ID ${value.meta.id}: ${known.name} in ${known.file} and ${name} in ${file}`);
      byId.set(value.meta.id, { id: value.meta.id, name, file });
    }
  }
  const byName = new Map();
  for (const check of byId.values()) {
    const known = byName.get(check.name);
    if (known) throw new Error(`duplicate check export name ${check.name}: ${known.id} and ${check.id}`);
    byName.set(check.name, check);
  }
  return [...byId.values()].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
}

const pascal = (id) => id.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join("");
const FORMAT_ID = /^[a-z][a-z0-9-]*$/;

/** Every format module (a module that exports `render`), as { id, file }, sorted by format ID. */
export async function discoverFormats(dir = FORMATS_DIST) {
  const out = [];
  for (const file of listModules(dir, ["index.js", "registry.js", "base.js"])) {
    const module = await import(pathToFileURL(join(dir, file)).href);
    if (typeof module.render !== "function") continue;
    const id = file.replace(/\.js$/, "");
    if (!FORMAT_ID.test(id)) throw new Error(`format file ${file} must be named <format-id>.js with a lowercase id (got "${id}")`);
    out.push({ id, file });
  }
  return out.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
}

const GENERATED = (what) => [
  `// GENERATED by tools/gen-registries.mjs — do not edit by hand.`,
  `// To add ${what}: create the module (see the folder's index.ts), run \`npm run build\`, then \`node tools/gen-registries.mjs\`.`,
  ``,
];

export function renderChecksRegistry(checks) {
  const namesByFile = new Map();
  for (const { name, file } of checks) namesByFile.set(file, [...(namesByFile.get(file) ?? []), name]);
  const lines = [
    ...GENERATED("a check"),
    `import type { Check } from "../types.js";`,
    ...[...namesByFile.entries()].map(([file, names]) => `import { ${names.sort().join(", ")} } from "./${file}";`),
    ``,
    `/** Every built-in check, sorted by check ID so the order never depends on the filesystem. */`,
    `export const builtInChecks: readonly Check[] = [`,
    ...checks.map(({ name }) => `  ${name},`),
    `];`,
    ``,
  ];
  return lines.join("\n");
}

export function renderFormatsRegistry(formats) {
  const lines = [
    ...GENERATED("a format"),
    `import { PLAIN, type Palette } from "../color.js";`,
    `import type { Report } from "../types.js";`,
    `import type { FormatContext } from "./base.js";`,
    ...formats.map(({ id, file }) => `import { render as render${pascal(id)} } from "./${file}";`),
    ``,
    `/** Every output format, sorted by format ID so the order never depends on the filesystem. */`,
    `export const FORMATS = [${formats.map(({ id }) => `"${id}"`).join(", ")}] as const;`,
    `export type Format = (typeof FORMATS)[number];`,
    ``,
    `export function formatReport(report: Report, format: Format, context: FormatContext = {}, paint: Palette = PLAIN): string {`,
    `  switch (format) {`,
    ...formats.map(({ id }) => `    case "${id}":\n      return render${pascal(id)}(report, context, paint);`),
    `  }`,
    `}`,
    ``,
  ];
  return lines.join("\n");
}

async function main() {
  const { values } = parseArgs({ options: { check: { type: "boolean" } } });
  const targets = [
    { path: CHECKS_REGISTRY, content: renderChecksRegistry(await discoverChecks()) },
    { path: FORMATS_REGISTRY, content: renderFormatsRegistry(await discoverFormats()) },
  ];
  const stale = [];
  for (const { path, content } of targets) {
    if (existsSync(path) && readFileSync(path, "utf8") === content) continue;
    stale.push(path);
    if (!values.check) {
      writeFileSync(path, content);
      console.log(`gen-registries: wrote ${path.replace(`${root}/`, "")}`);
    }
  }
  if (values.check && stale.length > 0) {
    console.error([
      `gen-registries: ${stale.map((p) => p.replace(`${root}/`, "")).join(", ")} ${stale.length === 1 ? "is" : "are"} out of date with the modules they collect.`,
      "gen-registries: run `npm run build && node tools/gen-registries.mjs` and commit the result.",
    ].join("\n"));
    process.exit(1);
  }
  if (stale.length === 0) console.log(`gen-registries: OK (built-in checks and formats registries are current)`);
}

// Run only when executed directly, not when imported by tests.
function invokedDirectly() {
  const entry = process.argv[1];
  if (!entry) return false;
  try {
    return realpathSync(entry) === fileURLToPath(import.meta.url);
  } catch {
    return false;
  }
}

if (invokedDirectly()) await main();
