// The reference generator must stay honest: a page is composed from the catalog and the prose page,
// never hand-written. See tools/gen-check-reference.mjs.

import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { test } from "node:test";

import { generatedFiles, loadCatalog, proseBody, renderReference } from "./gen-check-reference.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const DEMO = { id: "demo.rule", title: "A demo rule that reports a demo problem", severity: "warning", needs: ["html", "browser"], standards: ["WCAG 1.3.1"] };
const DEMO_PROSE = "# demo.rule\n\nOne sentence about the demo.\n\n## Why it matters\n\nSomeone is hurt.\n";

test("renderReference composes a catalog header over the prose, with one H1 and one trailing newline", () => {
  const page = renderReference(DEMO, "packages/verify/src/checks/demo.ts", DEMO_PROSE);
  const lines = page.split("\n");
  assert.match(lines[0], /^<!-- GENERATED by tools\/gen-check-reference\.mjs/);
  assert.equal(page.match(/^# /gm).length, 1, "the composed H1 replaces the prose H1; a page never carries two");
  assert.ok(page.includes("# demo.rule — A demo rule that reports a demo problem"));
  assert.ok(page.includes("- **Default severity:** `warning`; users can override it in `seaworthy.config.json`."));
  assert.ok(page.includes("- **Needs:** `html`, `browser` (only with `--rendered`)"));
  assert.ok(page.includes("- **Standards:** WCAG 1.3.1"));
  assert.ok(page.includes("- **Source module:** `packages/verify/src/checks/demo.ts`"));
  assert.ok(page.includes("[`docs/checks/demo.rule.md`](../demo.rule.md)"));
  assert.ok(page.includes("One sentence about the demo.\n\n## Why it matters\n\nSomeone is hurt.\n"), "the prose is embedded verbatim");
  assert.ok(page.endsWith("hurt.\n") && !page.endsWith("\n\n"));
});

test("renderReference names the network gate and says none when there are no standards", () => {
  const meta = { id: "demo.net", title: "A demo rule that reaches the network", severity: "note", needs: ["html", "network"], standards: [] };
  const page = renderReference(meta, "packages/verify/src/checks/net.ts", "# demo.net\n\nBody.\n");
  assert.ok(page.includes("- **Needs:** `html`, `network` (only with `--network`)"));
  assert.ok(page.includes("- **Standards:** none"));
});

test("proseBody requires the `# <id>` line, normalizes CRLF, and ends with exactly one newline", () => {
  assert.equal(proseBody("demo.rule", DEMO_PROSE), "One sentence about the demo.\n\n## Why it matters\n\nSomeone is hurt.\n");
  assert.equal(proseBody("demo.rule", "# demo.rule\r\n\r\nWindows prose.\r\n"), "Windows prose.\n");
  assert.throws(() => proseBody("demo.rule", "# other.id\n\nBody.\n"), /must start with "# demo\.rule"/);
  assert.throws(() => proseBody("demo.rule", "No heading at all.\n"), /must start with "# demo\.rule"/);
});

test("generatedFiles maps every catalog check to docs/checks/reference/<id>.md and fails on a missing prose page", () => {
  const dir = mkdtempSync(join(tmpdir(), "reference-"));
  mkdirSync(join(dir, "docs", "checks"), { recursive: true });
  writeFileSync(join(dir, "docs", "checks", "b.rule.md"), "# b.rule\n\nB prose.\n");
  writeFileSync(join(dir, "docs", "checks", "a.rule.md"), "# a.rule\n\nA prose.\n");
  const catalog = [
    { meta: { id: "b.rule", title: "B reports its own problem", severity: "error", needs: ["files"], standards: [] }, sourceRel: "packages/verify/src/checks/b.ts" },
    { meta: { id: "a.rule", title: "A reports its own problem", severity: "note", needs: ["html"], standards: [] }, sourceRel: "packages/verify/src/checks/a.ts" },
    { meta: { id: "c.rule", title: "C has no prose page", severity: "note", needs: ["html"], standards: [] }, sourceRel: "packages/verify/src/checks/c.ts" },
  ];
  assert.throws(() => generatedFiles(dir, catalog), /docs\/checks\/c\.rule\.md is missing/);
  const files = generatedFiles(dir, catalog.slice(0, 2));
  assert.deepEqual([...files.keys()], [join("docs", "checks", "reference", "b.rule.md"), join("docs", "checks", "reference", "a.rule.md")], "page order follows the catalog order it was given");
  assert.ok(files.get(join("docs", "checks", "reference", "a.rule.md")).includes("A prose.\n"));
});

test("the committed reference pages are exactly what the current catalog and prose generate", async () => {
  const files = generatedFiles(ROOT, await loadCatalog());
  const dir = join(ROOT, "docs", "checks", "reference");
  const onDisk = readdirSync(dir).filter((f) => f.endsWith(".md"));
  assert.deepEqual(onDisk.sort(), ["README.md", ...[...files.keys()].map((rel) => basename(rel)).sort()]);
  for (const [rel, content] of files) {
    assert.equal(readFileSync(join(ROOT, rel), "utf8"), content, rel);
  }
});
